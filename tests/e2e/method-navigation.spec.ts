test('catalog selects DSEM on an eligible 25-occasion ESM dataset and restores its custom settings', async ({ page }) => {
  test.setTimeout(120_000)
  const failures = await installPageFailureMonitor(page)
  await openAuthenticatedPage(page)
  await page.getByRole('button', { name: /分析已有数据/ }).click()
  await page.getByRole('radio', { name: /密集追踪/ }).click()
  await page.getByRole('radio', { name: /观测相互独立/ }).click()
  await page.getByLabel('选择数据文件').setInputFiles(path.resolve('samples/data/intensive-esm-demo.csv'))
  await page.getByRole('button', { name: '导入并创建数据版本' }).click()
  await expect(page.getByRole('heading', { name: '确认变量类型' })).toBeVisible()
  await page.getByLabel('person_id的最终类型').selectOption('id')
  for (const name of ['occasion', 'emotion', 'ai_trust']) await page.getByLabel(`${name}的最终类型`).selectOption('continuous')
  await page.getByRole('button', { name: '确认全部变量' }).click()
  await page.getByRole('combobox', { name: /个体 \/ 研究对象 ID/ }).selectOption({ label: 'person_id (person_id)' })
  await page.getByRole('combobox', { name: /波次 \/ 时间变量/ }).selectOption({ label: 'occasion (occasion)' })
  await page.getByRole('button', { name: '运行结构画像' }).click()
  await expect(page.getByText(/本次画像：/)).toBeVisible()
  const reason = page.getByLabel('继续使用的学术理由（至少 10 个字符）')
  if (await reason.isVisible()) await reason.fill('已核查每人二十五个测量时点，本次仅检查 DSEM 配置，不进行估计。')
  await page.getByRole('button', { name: '保存结构版本' }).click()
  const card = page.locator('.construct-card').first()
  await card.getByLabel('构念 1 名称').fill('日记测量')
  await card.getByLabel('理论最小值').fill('-10')
  await card.getByLabel('理论最大值').fill('10')
  for (const name of ['emotion', 'ai_trust']) await card.getByRole('checkbox', { name: `${name} ${name}`, exact: true }).check()
  await page.getByRole('button', { name: '保存规则并生成测量版本' }).click()
  await expect(page.getByRole('heading', { name: '日记与 ESM 分析中心', exact: true })).toBeVisible()
  await chooseMethod(page, '观测变量 Bayesian DSEM')
  await expect(page.getByRole('combobox', { name: '分析类型', exact: true })).toHaveValue('bayesian_dsem')
  await page.getByRole('spinbutton', { name: '每链迭代', exact: true }).fill('3000')
  await page.getByRole('combobox', { name: '结果变量 Y', exact: true }).selectOption({ label: 'exposure_minutes' })
  await page.getByRole('tab', { name: '方法目录', exact: true }).click()
  await page.getByRole('button', { name: '配置观测变量 Bayesian DSEM', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: '每链迭代', exact: true })).toHaveValue('3000')
  await expect(page.getByRole('combobox', { name: '结果变量 Y', exact: true }).locator('option:checked')).toHaveText('exposure_minutes')
  await page.reload()
  await expect(page.getByRole('combobox', { name: '分析类型', exact: true })).toHaveValue('bayesian_dsem')
  await expect(page.getByRole('spinbutton', { name: '每链迭代', exact: true })).toHaveValue('3000')
  await failures.expectClean()
})
